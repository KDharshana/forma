import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const rootDir = resolve(__dirname, "..");

function extractPropsFromFile(filePath, fileName, categoryPrefix) {
  const code = readFileSync(filePath, "utf8");
  const sf = ts.createSourceFile(fileName, code, ts.ScriptTarget.Latest, true);

  // 1. Find default parameter initializers
  const defaults = {};
  function findDefaults(node) {
    if (
      ts.isFunctionDeclaration(node) ||
      ts.isFunctionExpression(node) ||
      ts.isArrowFunction(node) ||
      ts.isVariableDeclaration(node)
    ) {
      let params = node.parameters;
      if (
        !params &&
        node.initializer &&
        (ts.isArrowFunction(node.initializer) ||
          ts.isFunctionExpression(node.initializer))
      ) {
        params = node.initializer.parameters;
      }
      if (params && params.length > 0) {
        const firstParam = params[0];
        if (firstParam.name && ts.isObjectBindingPattern(firstParam.name)) {
          firstParam.name.elements.forEach((el) => {
            if (el.name && ts.isIdentifier(el.name) && el.initializer) {
              defaults[el.name.text] = el.initializer.getText(sf);
            }
          });
        }
      }
    }
    ts.forEachChild(node, findDefaults);
  }
  findDefaults(sf);

  // 2. Find target Props interface or type
  const baseName = fileName.replace(/\.tsx?$/, "");
  let targetInterface = null;
  let targetInterfaceName = "";

  function findPropsNode(node) {
    if (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) {
      const name = node.name.text;
      if (name === `${baseName}Props` || name.endsWith("Props")) {
        if (!targetInterface || name === `${baseName}Props`) {
          targetInterface = node;
          targetInterfaceName = name;
        }
      }
    }
    ts.forEachChild(node, findPropsNode);
  }
  findPropsNode(sf);

  if (!targetInterface) {
    return null;
  }

  const props = [];
  const members = ts.isInterfaceDeclaration(targetInterface)
    ? targetInterface.members
    : ts.isTypeAliasDeclaration(targetInterface) &&
        ts.isTypeLiteralNode(targetInterface.type)
      ? targetInterface.type.members
      : [];

  members.forEach((member) => {
    if (ts.isPropertySignature(member)) {
      const propName = member.name.getText(sf);
      const propType = member.type ? member.type.getText(sf) : "any";
      const optional = !!member.questionToken;
      let description = "";

      const jsDoc = member.jsDoc;
      if (jsDoc && jsDoc.length > 0) {
        description = jsDoc
          .map((d) => (typeof d.comment === "string" ? d.comment : ""))
          .join(" ")
          .trim();
      }

      props.push({
        name: propName,
        type: propType,
        optional,
        defaultValue: defaults[propName] || undefined,
        description: description || "",
      });
    }
  });

  return {
    interfaceName: targetInterfaceName,
    fileName,
    path: `${categoryPrefix}/${fileName}`,
    propsCount: props.length,
    props,
  };
}

const compDir = resolve(rootDir, "components");
const compFiles = readdirSync(compDir).filter(
  (f) => f.endsWith(".tsx") && f !== "index.ts" && f !== "theme.ts",
);

const blockDir = resolve(rootDir, "blocks");
const blockFiles = existsSync(blockDir)
  ? readdirSync(blockDir).filter((f) => f.endsWith(".tsx") && f !== "index.ts")
  : [];

const registry = {};

for (const file of compFiles) {
  const extracted = extractPropsFromFile(resolve(compDir, file), file, "components");
  if (extracted) {
    registry[file] = extracted;
    registry[`components/${file}`] = extracted;
  }
}

for (const file of blockFiles) {
  const extracted = extractPropsFromFile(resolve(blockDir, file), file, "blocks");
  if (extracted) {
    registry[file] = extracted;
    registry[`blocks/${file}`] = extracted;
  }
}

const outputFile = resolve(rootDir, "showcase", "propsRegistry.ts");
const content = `// Generated by scripts/generate-props.mjs. Do not edit manually.

export interface PropDoc {
  name: string;
  type: string;
  optional: boolean;
  defaultValue?: string;
  description: string;
}

export interface ComponentPropsDoc {
  interfaceName: string;
  fileName: string;
  path: string;
  propsCount: number;
  props: PropDoc[];
}

export const propsRegistry: Record<string, ComponentPropsDoc> = ${JSON.stringify(
  registry,
  null,
  2,
)};
`;

writeFileSync(outputFile, content, "utf8");
console.log(
  `Generated props registry for ${compFiles.length} components and ${blockFiles.length} blocks (${Object.keys(registry).length / 2} unique modules) at showcase/propsRegistry.ts.`,
);
