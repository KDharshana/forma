import { readdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";

const compFiles = (
  await readdir(new URL("../components/", import.meta.url))
).filter((file) => /\.tsx?$/.test(file));

let blockFiles = [];
const blocksDir = new URL("../blocks/", import.meta.url);
if (existsSync(blocksDir)) {
  blockFiles = (await readdir(blocksDir)).filter((file) =>
    /\.tsx?$/.test(file),
  );
}

const compSources = await Promise.all(
  compFiles.map(async (file) => [
    `components/${file}`,
    await readFile(new URL(`../components/${file}`, import.meta.url), "utf8"),
  ]),
);

const blockSources = await Promise.all(
  blockFiles.map(async (file) => [
    `blocks/${file}`,
    await readFile(new URL(`../blocks/${file}`, import.meta.url), "utf8"),
  ]),
);

const sources = Object.fromEntries([...compSources, ...blockSources]);

await writeFile(
  new URL("../showcase/sources.ts", import.meta.url),
  `// Generated by npm run sources. Do not edit manually.\nexport const sources: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n`,
);
console.log(
  `Updated source previews for ${compFiles.length} components and ${blockFiles.length} blocks (${Object.keys(sources).length} total).`,
);
